-- TEST 4: Verify cascading DELETE

-- Use a transaction so the original sample data is restored.

BEGIN;

DELETE FROM projects
WHERE tenant_id = 1
  AND project_id = 1;

DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM tasks
        WHERE tenant_id = 1 AND project_id = 1
    ) THEN
        RAISE EXCEPTION 'FAIL: Related tasks were not deleted';
    END IF;

    IF EXISTS (
        SELECT 1 FROM project_members
        WHERE tenant_id = 1 AND project_id = 1
    ) THEN
        RAISE EXCEPTION 'FAIL: Project members were not deleted';
    END IF;

    RAISE NOTICE 'PASS: Project deletion cascaded to tasks and project members';
END $$;

ROLLBACK;



-- TEST 5: Verify cascading UPDATE

-- Temporarily allow manual identity values.
-- The transaction rollback restores the original setting.

BEGIN;

ALTER TABLE tenants
ALTER COLUMN tenant_id SET GENERATED BY DEFAULT;

UPDATE tenants
SET tenant_id = 101
WHERE tenant_id = 1;

DO $$
BEGIN
    
IF EXISTS (
    SELECT 1 FROM projects
    WHERE tenant_id = 101
)
AND EXISTS (
    SELECT 1 FROM tenant_memberships
    WHERE tenant_id = 101
)
AND EXISTS (
    SELECT 1 FROM tenant_settings
    WHERE tenant_id = 101
)
AND EXISTS (
    SELECT 1 FROM tasks
    WHERE tenant_id = 101
)
AND EXISTS (
    SELECT 1 FROM project_members
    WHERE tenant_id = 101
) THEN

    RAISE NOTICE
    'PASS: Tenant ID update cascaded to all related tables';

ELSE
    RAISE EXCEPTION
    'FAIL: Tenant ID update did not cascade correctly';
END IF;

END $$;

ROLLBACK;



