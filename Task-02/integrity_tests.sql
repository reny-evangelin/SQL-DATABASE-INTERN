-- TEST 1: Reject a task with a non-existent project

DO $$
BEGIN
    BEGIN
        INSERT INTO tasks
            (tenant_id, project_id, title)
        VALUES
            (1, 9999, 'Invalid project task');

        RAISE EXCEPTION 'FAIL: Invalid project was accepted';

    EXCEPTION
        WHEN foreign_key_violation THEN
            RAISE NOTICE 'PASS: Invalid project reference rejected';
    END;
END $$;


-- TEST 2: Reject cross-tenant project membership

-- Rahul (user 2) belongs to Tenant 1.
-- Project 3 belongs to Tenant 2.
-- Rahul cannot join Tenant 2's project without membership there.

DO $$
BEGIN
    BEGIN
        INSERT INTO project_members
            (tenant_id, project_id, user_id)
        VALUES
            (2, 3, 2);

        RAISE EXCEPTION 'FAIL: Cross-tenant assignment was accepted';

    EXCEPTION
        WHEN foreign_key_violation THEN
            RAISE NOTICE 'PASS: Cross-tenant assignment rejected';
    END;
END $$;


